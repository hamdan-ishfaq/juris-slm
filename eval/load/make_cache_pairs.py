def main() -> int:
    golden = {json.loads(line)["id"]: json.loads(line)["question"]
              for line in (ROOT / "eval" / "golden" / "law_qa.jsonl").read_text().splitlines() if line.strip()}
    rows = []
    for qid, (hits, misses) in PAIRS.items():
        for probe in hits:
            rows.append({"id": qid, "cached": golden[qid], "probe": probe, "expect": "hit", "kind": "paraphrase"})
        for kind, probe in misses + EXTRA_MISSES.get(qid, []):
            rows.append({"id": qid, "cached": golden[qid], "probe": probe, "expect": "miss", "kind": kind})
    out = ROOT / "eval" / "load" / "cache_pairs.jsonl"
    out.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    print(f"{len(rows)} pairs: {sum(r['expect'] == 'hit' for r in rows)} hit, {sum(r['expect'] == 'miss' for r in rows)} miss")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
